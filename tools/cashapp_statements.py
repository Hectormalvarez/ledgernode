#!/usr/bin/env python3
"""Extract Cash App account statements (PDF) into one verified CSV.

Why this exists
---------------
Capital One's export shows money leaving checking for "CASH APP" as a single
anonymous line.  What that money was actually spent on only exists inside Cash
App's monthly statement PDFs.  Those PDFs are generated by openhtmltopdf, so
their text layer is clean and the tables survive `pdftotext -layout`.

The rule this tool follows is the same one `verify_import.py` follows: never
trust a total you produced yourself.  Each statement prints its own
"Money In" and "Money Out"; after parsing, those figures are recomputed from
the extracted rows and must agree, or the run fails.

Usage
-----
    python3 tools/cashapp_statements.py --dir ~/Desktop/cashapp
    python3 tools/cashapp_statements.py --dir ~/Desktop/cashapp --csv out.csv
    python3 tools/cashapp_statements.py --dir ~/Desktop/cashapp --verbose

Exit codes: 0 = every statement reconciled, 1 = at least one did not,
2 = nothing parsed at all (missing pdftotext, wrong directory, no PDFs).
"""

from __future__ import annotations

import argparse
import csv
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from decimal import Decimal

MONTHS = "Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec"

ROW_RE = re.compile(rf"^\s*({MONTHS})\s+(\d{{1,2}})\s+(.*)$")
MONEY_RE = re.compile(r"([+-]?)\s*\$(\d[\d,]*\.\d{2})")
MONEY_IN_RE = re.compile(r"Money In\s+\+\s*\$([\d,]*\.?\d{2})")
MONEY_OUT_RE = re.compile(r"Money Out\s+-\s*\$([\d,]*\.?\d{2})")
MONTH_RE = re.compile(r"Account Statement - (\w+) (\d{4})")
SKIP_RE = re.compile(
    r"^(Transactions|Date\s+Description|PLEASE SEE NOTICE|Cash App$|"
    r"\d+\s*/\s*\d+$|Balance on|Change this month|Fees$|Money In|Money Out)"
)
# A payment funded directly by a linked bank or card never touches the Cash App
# balance, so the statement lists it but excludes it from Money Out:
#   "To Sample Partner from U.S. Bank x0002   Cash App payment   $0.00   $300.00"
# The trailing account digits are sometimes wrapped onto the next line and
# sometimes absent altogether, so the reliable signal is the phrasing itself:
# "To <person> from <something>" means the money came from that something, not
# from the Cash App balance.
BANK_FUNDED_RE = re.compile(r"^\s*to\s+.+?\bfrom\b", re.IGNORECASE)
# Page furniture that can trail a wrapped row and must never be treated as text.
FOOTER_RE = re.compile(r"(\d+\s*/\s*\d+|\bAccount Statement\b|^(Jan|Feb|Mar|Apr|May|Jun|"
                       r"Jul|Aug|Sep|Oct|Nov|Dec)\w*\s+\d{4}$)")
BORROW_RE = re.compile(r"overdraft coverage repayment|loan repayment", re.IGNORECASE)
# "Cash App Pay" is Cash App's checkout method (like Apple Pay). When it is
# funded by a linked card the money never touches the Cash App balance either,
# even though the row is listed. January 2026: the single $24.89 Google row is
# exactly the gap between the parsed outflow and the stated Money Out.
CASH_APP_PAY_RE = re.compile(r"\bcash app pay\b(?!ment)", re.IGNORECASE)



@dataclass
class Row:
    month: str
    day: str
    description: str
    fee: Decimal
    amount: Decimal  # signed: positive = money in
    source: str
    bank_funded: bool = False  # paid directly by a linked bank/card, never touched the balance
    category: str = ""


def pdf_to_text(path: str) -> str:
    """Return the laid-out text of a PDF, or exit if pdftotext is missing."""
    try:
        proc = subprocess.run(
            ["pdftotext", "-layout", path, "-"],
            capture_output=True,
            text=True,
            check=True,
        )
    except FileNotFoundError as exc:  # pragma: no cover - environment guard
        raise SystemExit(
            "pdftotext not found. Install poppler-utils (apt install poppler-utils)."
        ) from exc
    return proc.stdout


def split_money(text: str) -> tuple[Decimal, Decimal, str] | None:
    """Split a row into (fee, amount, description) using the last two money fields.

    Both the fee column and the amount column are always present. Anything to
    the left of the fee column is the description plus details text.
    """
    hits = list(MONEY_RE.finditer(text))
    if len(hits) < 2:
        return None
    fee_hit, amount_hit = hits[-2], hits[-1]
    description = text[: fee_hit.start()].strip()
    if not description:
        return None
    fee = Decimal(fee_hit.group(2).replace(",", ""))
    magnitude = Decimal(amount_hit.group(2).replace(",", ""))
    amount = magnitude if amount_hit.group(1) == "+" else -magnitude
    return fee, amount, description


def categorize(row: Row) -> str:
    """Label a row by what it actually did to the household's money.

    The same statement mixes four very different things: money arriving, borrowing
    being repaid, purchases, and payments funded by a linked bank that never
    touched the Cash App balance at all. Treating them alike is how a ledger lies.
    """
    text = row.description.lower()
    if BORROW_RE.search(text):
        return "borrow_repayment"
    if row.bank_funded and row.amount < 0:
        return "bank_funded_payment"
    if row.amount > 0:
        if "direct deposit" in text:
            return "payroll_in"
        if "standard transfer" in text or "from " in text:
            return "transfer_in"
        return "payment_in"
    if "cash app card" in text:
        return "card_purchase"
    if CASH_APP_PAY_RE.search(text):
        return "cash_app_pay_external"
    return "payment_out"


def balance_affecting(rows: list[Row]) -> list[Row]:
    """Rows that moved the Cash App balance, which is what the statement totals count.

    Payments funded directly by a linked bank appear on the statement but are left
    out of its Money In / Money Out figures, because the money never sat in the
    Cash App balance. Proved on August 2026: stated out $203.00; parsed out
    excluding bank-funded rows $203.00; bank-funded rows $1,708.00.

    Known limitation: Cash App also prints a few balance-exempt rows that carry no
    marker distinguishing them from real outflows (January 2026 has one $24.89
    "Cash App Pay" row that is in neither figure). Excluding "Cash App Pay" rows
    wholesale over-corrects badly, so the tool reports the residual per statement
    rather than hiding it. Money In reconciles exactly on every statement; Money
    Out is exact on most and within a few dollars on the rest.
    """
    return [r for r in rows if not (r.bank_funded and r.amount < 0)]


def parse_statement(path: str) -> tuple[list[Row], Decimal | None, Decimal | None]:
    """Parse one statement PDF into rows plus its own declared in/out totals."""
    text = pdf_to_text(path)
    name = os.path.basename(path)

    money_in = MONEY_IN_RE.search(text)
    money_out = MONEY_OUT_RE.search(text)
    rows: list[Row] = []

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or SKIP_RE.match(stripped):
            continue
        row_match = ROW_RE.match(line)
        if not row_match:
            # A wrapped description, e.g. "x0001" sitting under "To Sample Person
            # from Capital One Bank". It belongs to the row ABOVE it, never the
            # row below, and page furniture such as "4/6" or "August 2026 Account
            # Statement" must never be absorbed into either.
            if (
                rows
                and len(stripped) < 60
                and not stripped.isdigit()
                and not FOOTER_RE.search(stripped)
            ):
                previous = rows[-1]
                previous.description = f"{previous.description} {stripped}".strip()
                previous.bank_funded = bool(BANK_FUNDED_RE.search(previous.description))
                previous.category = categorize(previous)
            continue
        parts = split_money(row_match.group(3))
        if parts is None:
            continue
        fee, amount, description = parts
        clean = re.sub(r"\s{2,}", " | ", description)
        row = Row(
            month=row_match.group(1),
            day=row_match.group(2),
            description=clean,
            fee=fee,
            amount=amount,
            source=name,
            bank_funded=bool(BANK_FUNDED_RE.search(clean)),
        )
        row.category = categorize(row)
        rows.append(row)

    declared_in = Decimal(money_in.group(1).replace(",", "")) if money_in else None
    declared_out = Decimal(money_out.group(1).replace(",", "")) if money_out else None
    return rows, declared_in, declared_out


def totals(rows: list[Row]) -> tuple[Decimal, Decimal]:
    money_in = sum((r.amount for r in rows if r.amount > 0), Decimal("0.00"))
    money_out = sum((-r.amount for r in rows if r.amount < 0), Decimal("0.00"))
    return money_in, money_out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Extract Cash App statement PDFs to CSV.")
    parser.add_argument("--dir", required=True, help="directory holding the statement PDFs")
    parser.add_argument("--csv", help="write the extracted rows here")
    parser.add_argument("--verbose", action="store_true", help="print every row")
    args = parser.parse_args(argv)

    if not os.path.isdir(args.dir):
        print(f"not a directory: {args.dir}", file=sys.stderr)
        return 2
    candidates = sorted(
        os.path.join(args.dir, f)
        for f in os.listdir(args.dir)
        if f.lower().endswith(".pdf")
    )
    if not candidates:
        print(f"no PDFs in {args.dir}", file=sys.stderr)
        return 2

    # The same statement is easy to download twice, and one file here carries a
    # newline in its name ("February 2026\n.pdf") so it looks like two files and
    # hashes differently. Normalise whitespace out of the name instead, or
    # February is counted twice and every total is wrong.
    pdfs: list[str] = []
    seen: dict[str, str] = {}
    for path in candidates:
        key = re.sub(r"\s+", "", os.path.basename(path)).lower()
        if key in seen:
            print(
                f"skipping duplicate statement: {path!r} "
                f"== {seen[key]!r}"
            )
            continue
        seen[key] = path
        pdfs.append(path)

    all_rows: list[Row] = []
    failures = 0
    header = (
        f"{'statement':<20}{'rows':>6}{'in (parsed)':>14}{'in (stated)':>14}"
        f"{'out (parsed)':>14}{'out (stated)':>14}  verdict"
    )
    print(header)
    print("-" * len(header))
    for path in pdfs:
        rows, declared_in, declared_out = parse_statement(path)
        parsed_in, parsed_out = totals(balance_affecting(rows))
        residual = parsed_out - (declared_out or Decimal(0))
        ok_in = declared_in is None or parsed_in == declared_in
        ok_out = declared_out is None or parsed_out == declared_out
        verdict = "reconciled" if (ok_in and ok_out) else f"out residual {residual:+,.2f}"
        failures += 0 if (ok_in and ok_out) else 1
        label = os.path.basename(path)
        label = label.replace("eltoritolocito - Account Statement - ", "")
        label = label[:-4] if label.lower().endswith(".pdf") else label
        label = re.sub(r"\s+", " ", label).strip()
        print(
            f"{label:<20}{len(rows):>6}{parsed_in:>14,.2f}"
            f"{(declared_in or Decimal(0)):>14,.2f}"
            f"{parsed_out:>14,.2f}"
            f"{(declared_out or Decimal(0)):>14,.2f}  {verdict}"
        )
        all_rows.extend(rows)

    all_rows.sort(key=lambda r: (r.month, int(r.day)))
    if args.verbose:
        for r in all_rows:
            print(f"  {r.month} {r.day:>2} {r.amount:>12,.2f}  {r.description}", file=sys.stderr)

    if args.csv:
        with open(args.csv, "w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(
                ["month", "day", "description", "category", "fee", "amount", "source"]
            )
            for r in all_rows:
                writer.writerow(
                    [
                        r.month,
                        r.day,
                        r.description,
                        r.category,
                        f"{r.fee:.2f}",
                        f"{r.amount:.2f}",
                        r.source,
                    ]
                )
        print(f"\nwrote {len(all_rows)} rows to {args.csv}")

    total_in, total_out = totals(all_rows)
    print(f"\n{len(all_rows)} rows across {len(pdfs)} statements")
    print(f"money in {total_in:,.2f}   money out {total_out:,.2f}")

    buckets: dict[str, tuple[int, Decimal]] = {}
    for r in all_rows:
        count, running = buckets.get(r.category, (0, Decimal("0.00")))
        buckets[r.category] = (count + 1, running + (r.amount if r.amount > 0 else -r.amount))
    print(f"\n{'category':<22}{'rows':>6}{'total':>14}")
    for name, (count, running) in sorted(buckets.items(), key=lambda kv: -kv[1][1]):
        print(f"{name:<22}{count:>6}{running:>14,.2f}")

    if failures:
        print(f"FAILED: {failures} statement(s) did not reconcile", file=sys.stderr)
        return 1
    print("all statements reconciled against their own printed totals")
    return 0


if __name__ == "__main__":
    sys.exit(main())
